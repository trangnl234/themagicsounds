interface RawSpeldBookSpec {
  id: number;
  group: number;
  bookNumber: number;
  flipbookId: string;
  stars: 1 | 2;
  title: string;
  author: string;
  customSounds?: string[];
  blendingWords: string[];
  trickyWords: string[];
  pages: string[][];
}

function createSpeldBook(spec: RawSpeldBookSpec): DecodableBook {
  const sounds = spec.customSounds || SPELD_SOUNDS_BY_SET[spec.group] || SPELD_SOUNDS_BY_SET[1];
  const allSentences = spec.pages.map((pLines) => pLines.join(' '));
  return {
    id: spec.id,
    group: spec.group,
    bookNumber: spec.bookNumber,
    flipbookId: spec.flipbookId,
    stars: spec.stars,
    title: spec.title,
    author: spec.author,
    synopsis: spec.title,
    wordCount: allSentences.join(' ').split(/\s+/).length,
    diamonds: 15,
    illustration: '',
    illustrationAlt: `${spec.title} - SPELD SA Set ${spec.group}`,
    captionVi: '',
    targetWords: [
      ...spec.blendingWords.map((word) => ({ word })),
      ...spec.trickyWords.map((word) => ({ word, isTricky: true })),
    ],
    practicePage: {
      sounds,
      blendingWords: spec.blendingWords,
      trickyWords: spec.trickyWords,
      vocabulary: [],
    },
    pages: spec.pages.map((pLines, idx) => ({
      pageNumber: idx + 1,
      lines: buildSpeldStoryLines(pLines, spec.trickyWords),
      captionVi: '',
    })),
    lines: buildSpeldStoryLines(allSentences, spec.trickyWords),
  };
}

